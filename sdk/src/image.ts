import { sha256 } from '@noble/hashes/sha2.js';
import type { GatewayClient } from './index.js';

export interface ImageReference { id: string; bytes: Uint8Array; mimeType: 'image/png' | 'image/jpeg'; name?: string }
export interface ImageProgress { stage: 'queued' | 'generating' | 'finishing'; percent: number }
export interface GatewayImage {
  request_id: string; data: string; mime_type: 'image/png' | 'image/jpeg';
  width: number; height: number; sha256: string; source_image_ids: string[];
  chat_model_id?: string; evidence: Record<string,unknown>; usage: Record<string,unknown>;
}
interface Options {
  model: string; prompt: string; references?: ImageReference[];
  dimensions?: { width: number; height: number }; aspectRatio?: string;
}
const hex = (value: Uint8Array) => Array.from(value,b=>b.toString(16).padStart(2,'0')).join('');
const MAX_DATA = 12 * 1024 * 1024;

/** Uploads and generated bytes stay in the browser and the attested endpoints.
 * Images are returned only after authenticated terminal/EOF and content binding. */
export async function requestImage(client: GatewayClient, options: Options, progress?: (value: ImageProgress)=>void, signal?: AbortSignal): Promise<GatewayImage> {
  const references = options.references ?? [];
  if (!options.model || !options.prompt.trim() || new TextEncoder().encode(options.prompt).length > 8192 || references.length > 5 ||
      new Set(references.map(r=>r.id)).size !== references.length || references.some(r=>!r.id || r.id.length>128 || /[\u0000-\u001f\u007f]/.test(r.id)) ||
      options.dimensions && options.aspectRatio) throw new Error('Provide a prompt and at most five ordered reference images');
  const requestId = crypto.randomUUID().replaceAll('-','');
  const release = client.retain();
  let started = false;
  try {
    const bindings: Array<{ id: string; upload_id: string }> = [];
    for (const [i, reference] of references.entries()) {
      const upload = await client.upload({ bytes:reference.bytes, targetRequestId:requestId, model:options.model, kind:'image', name:reference.name ?? `reference-${i+1}.png`, mimeType:reference.mimeType }, signal);
      bindings.push({ id:reference.id, upload_id:upload });
    }
    const chunks: string[] = []; let length = 0; let previous: ImageProgress | undefined;
    started = true;
    const value = await client.rpc({ op:'image', model:options.model, prompt:options.prompt, references:bindings,
      ...(options.dimensions ? { dimensions:options.dimensions } : {}), ...(options.aspectRatio ? { aspect_ratio:options.aspectRatio } : {}) }, frame=>{
      if (frame.kind === 'image_chunk') {
        const chunk = frame.data as { offset?: unknown; data?: unknown };
        if (chunk.offset !== length || typeof chunk.data !== 'string' || !/^[A-Za-z0-9+/]*={0,2}$/.test(chunk.data) || chunk.data.length%4 || length+chunk.data.length>MAX_DATA) throw new Error('Invalid generated image chunk');
        chunks.push(chunk.data); length += chunk.data.length;
      } else if (frame.kind === 'image_progress') {
        const next = frame.data as ImageProgress;
        const stages = ['queued','generating','finishing'];
        if (!stages.includes(next.stage) || !Number.isInteger(next.percent) || next.percent<0 || next.percent>99 ||
            previous && (stages.indexOf(next.stage)<stages.indexOf(previous.stage) || next.percent<previous.percent)) throw new Error('Invalid image progress');
        previous = next; progress?.(next);
      }
    }, { ...(signal ? { signal } : {}), requestId }) as { upstream_response_verified?: boolean; image?: Omit<GatewayImage,'data'>; image_data_length?: number };
    const image = value.image;
    if (value.upstream_response_verified !== true || !image || value.image_data_length !== length || !length ||
        !['image/png','image/jpeg'].includes(image.mime_type) || !/^[a-f0-9]{64}$/.test(image.sha256) ||
        !Number.isInteger(image.width) || !Number.isInteger(image.height) || image.width<=0 || image.height<=0 || image.width*image.height>2359296 ||
        JSON.stringify(image.source_image_ids ?? []) !== JSON.stringify(references.map(r=>r.id)) || image.usage?.responseVerified !== true || image.usage?.requestId !== image.request_id) throw new Error('Generated image binding failed');
    const data = chunks.join('');
    const bytes = Uint8Array.from(atob(data),char=>char.charCodeAt(0));
    try {
      if (hex(sha256(bytes)) !== image.sha256) throw new Error('Generated image content digest failed');
    } finally { bytes.fill(0); }
    return { ...image, source_image_ids:image.source_image_ids ?? [], data };
  } catch(error) {
    if (started) await client.rpc({ op:'cancel', target_request_id:requestId },()=>{}, { signal:AbortSignal.timeout(5000) }).catch(()=>{});
    await client.rpc({ op:'upload_abort', target_request_id:requestId },()=>{}, { signal:AbortSignal.timeout(5000) }).catch(()=>{});
    throw error;
  } finally { release(); }
}
